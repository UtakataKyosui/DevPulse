// 管理画面(React + shadcn/ui)を 1 本の JS と CSS にまとめ、Worker に文字列として埋め込む。
// 出力は src/worker/admin/generated.ts(git 管理外)。公開ビルド(doc_build)には含めない。
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/worker/admin/generated.ts');

const js = await build({
  entryPoints: [path.join(root, 'src/admin/main.tsx')],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  target: 'es2022',
  jsx: 'automatic',
  legalComments: 'none',
  tsconfig: path.join(root, 'tsconfig.json'),
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
});
const script = js.outputFiles[0]?.text;
if (!script) throw new Error('esbuild produced no output');

const css = execFileSync(
  path.join(root, 'node_modules/.bin/tailwindcss'),
  ['--input', path.join(root, 'src/admin/admin.css'), '--minify'],
  { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
);

writeFileSync(
  out,
  `// Generated by scripts/build-admin.ts. Do not edit.\nexport const ADMIN_JS = ${JSON.stringify(script)};\nexport const ADMIN_CSS = ${JSON.stringify(css)};\n`,
);
console.log(
  `admin: ${(script.length / 1024).toFixed(0)} KiB js, ${(css.length / 1024).toFixed(0)} KiB css`,
);
