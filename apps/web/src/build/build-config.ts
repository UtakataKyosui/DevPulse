import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import * as path from 'node:path';
import { projectConfigSchema } from '@devpulse/domain/devpulse/schema';
import type { ProjectDefinition } from '@devpulse/domain/devpulse/types';
import { buildProjectSidebar } from './project-sidebar.ts';

export const PROJECTS_CACHE = '.projects-cache/config.json';
export const FIXTURE_ENV = 'DEVPULSE_PROJECTS_FIXTURE';
/** 生成ページに入れる印。これを持たない index.mdx は手書きとして扱い、上書き・削除しない。 */
export const GENERATED_MARKER = '{/* generated by projects:fetch */}';

/** Worker の公開 API から設定を取得する。失敗は例外にして呼び出し側(ビルド)を止める。 */
export async function fetchPublishedProjects(
  origin: URL,
  fetchImpl: typeof fetch = fetch,
): Promise<ProjectDefinition[]> {
  const response = await fetchImpl(new URL('/api/projects', origin), {
    redirect: 'error',
    signal: AbortSignal.timeout(60000),
  });
  if (!response.ok)
    throw new Error(`Projects API returned HTTP ${response.status}`);
  return projectConfigSchema.parse(await response.json()).projects;
}

/**
 * ビルドで使う設定を読む。環境変数で fixture を明示したときだけ fixture を使い、
 * 取得結果がないときに fixture へ切り替えず失敗する。
 */
export function loadBuildProjects(
  root: string,
  env: Record<string, string | undefined> = process.env,
): ProjectDefinition[] {
  const fixture = env[FIXTURE_ENV];
  const file = fixture
    ? path.resolve(root, fixture)
    : path.join(root, PROJECTS_CACHE);
  if (!existsSync(file))
    throw new Error(
      fixture
        ? `${FIXTURE_ENV} file not found: ${fixture}`
        : `Project config not fetched (${PROJECTS_CACHE}). Run "pnpm run projects:fetch", or set ${FIXTURE_ENV} to use a fixture.`,
    );
  return projectConfigSchema.parse(JSON.parse(readFileSync(file, 'utf8')))
    .projects;
}

function generatedPage(project: ProjectDefinition): string {
  const heading = project.name.replace(/[\\`*_{}<>[\]]/g, '\\$&');
  return `---
title: ${JSON.stringify(project.name)}
description: ${JSON.stringify(project.description)}
---

${GENERATED_MARKER}

import {
  IssueThroughput,
  MilestoneList,
  NextActions,
  ProjectDetail,
  ProjectOverview,
  ProjectStatus,
  RecentActivity,
} from '../../../src/components/devpulse/ProjectDetail.tsx';

# ${heading}

<ProjectDetail slug=${JSON.stringify(project.slug)}>

## 概要

<ProjectOverview />

## 現在地

<ProjectStatus />

## Milestones

<MilestoneList />

## Issue 進捗

<IssueThroughput />

## 最近の活動

<RecentActivity />

## 次にやること

<NextActions />

</ProjectDetail>
`;
}

function writeIfChanged(file: string, content: string) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== content)
    writeFileSync(file, content);
}

/**
 * サイドバー(_meta.json)と詳細ページを設定に合わせる。
 * 公開プロジェクトは手書き MDX を優先し、無ければ汎用テンプレートから生成する。
 * 戻り値は、公開対象外の手書き MDX をビルドから外す route.exclude 用パターン。
 */
export function syncProjectPages(
  projectsDir: string,
  projects: ProjectDefinition[],
): string[] {
  writeIfChanged(
    path.join(projectsDir, '_meta.json'),
    `${JSON.stringify(buildProjectSidebar(projects), null, 2)}\n`,
  );

  const published = new Map(
    projects.filter((p) => p.published).map((p) => [p.slug, p]),
  );
  const generated = new Set<string>();
  const excluded: string[] = [];
  for (const entry of readdirSync(projectsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const page = path.join(projectsDir, entry.name, 'index.mdx');
    const isGenerated =
      existsSync(page) && readFileSync(page, 'utf8').includes(GENERATED_MARKER);
    if (isGenerated && published.has(entry.name)) generated.add(entry.name);
    else if (isGenerated)
      rmSync(path.join(projectsDir, entry.name), { recursive: true });
    else if (!published.has(entry.name))
      excluded.push(`projects/${entry.name}/**`);
  }
  for (const [slug, project] of published) {
    const dir = path.join(projectsDir, slug);
    if (existsSync(path.join(dir, 'index.mdx')) && !generated.has(slug))
      continue;
    mkdirSync(dir, { recursive: true });
    writeIfChanged(path.join(dir, 'index.mdx'), generatedPage(project));
    generated.add(slug);
  }
  // 生成ページは追跡しない(このファイル自体はルートの .gitignore で除外)。
  writeIfChanged(
    path.join(projectsDir, '.gitignore'),
    `${[...generated]
      .sort()
      .map((slug) => `/${slug}/`)
      .join('\n')}\n`,
  );
  return excluded;
}
